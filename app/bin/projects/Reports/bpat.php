        // rename the sheet
        $objSheet->setTitle('Unused Address Objects');
        // write header
        $objSheet->getCell('A1')->setValue('NAME');
        $objSheet->getCell('B1')->setValue('IP ADDRESS');
        $objSheet->getCell('C1')->setValue('DESCRIPTION');
